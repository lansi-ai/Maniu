#!/usr/bin/env node
// T-177 profile 切片的落地工具：把 desktop-profile.slice.yml 的某一波追加到
// 本检出的桌面 profile 运行副本，或撤回。
//
//   node lcoder/scripts/profile-slice.mjs apply --wave 1 --wave 2
//   node lcoder/scripts/profile-slice.mjs status
//   node lcoder/scripts/profile-slice.mjs restore
//   node lcoder/scripts/profile-slice.mjs estimate --wave 1
//
// 运行副本是 `apps/desktop/.desktop-build/development/home/profiles/desktop/cordis.patch.yml`，
// 被 `lcoder\scripts\rebuild.cmd profile` 重写；重写后切片自动消失。
// `estimate` 只读本检出的客户端构建产物（packages/client/*/lib/client.js），
// 不是运行时实际传输字节；真实字节在 `lcoder/profile-slice.md` 的测量一节记录。

import { readFileSync, writeFileSync, existsSync, copyFileSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const SLICE = join(ROOT, 'lcoder', 'desktop-profile.slice.yml')
const RUNTIME = join(
  ROOT, 'apps', 'desktop', '.desktop-build', 'development', 'home', 'profiles', 'desktop', 'cordis.patch.yml',
)
const BACKUP = `${RUNTIME}.t177-backup`
const BEGIN = '# ── T-177 slice begin'
const END = '# ── T-177 slice end'
const WAVE_HEADING = /^# ── T-177 slice · wave (\d+).*$/gm
const NOT_DISABLED_HEADING = /^# ── 明确不关的行/m

/** Split the slice file into wave number -> row text (comments kept). */
function readWaves() {
  const text = readFileSync(SLICE, 'utf8')
  const marks = [...text.matchAll(WAVE_HEADING)]
  const stop = text.search(NOT_DISABLED_HEADING)
  const waves = new Map()
  for (let i = 0; i < marks.length; i += 1) {
    const number = Number(marks[i][1])
    const start = marks[i].index + marks[i][0].length
    const nextWave = i + 1 < marks.length ? marks[i + 1].index : text.length
    const end = stop >= start ? Math.min(nextWave, stop) : nextWave
    waves.set(number, text.slice(start, end).trim())
  }
  return waves
}

/** Remove an existing generated block, if any. */
function stripBlock(text) {
  const begin = text.indexOf(BEGIN)
  if (begin < 0) return text
  const end = text.indexOf(END, begin)
  if (end < 0) throw new Error(`运行副本里 ${BEGIN} 没有对应的 ${END}；先人工核对再动手`)
  return text.slice(0, begin) + text.slice(end + END.length)
}

function parseRows(text) {
  const require2 = createRequire(join(ROOT, 'packages', 'lcoder', 'kernel', 'package.json'))
  const YAML = require2('yaml')
  return YAML.parse(text, { customTags: [{ tag: '!!js', resolve: value => String(value) }] })
}

function apply(selected) {
  const waves = readWaves()
  for (const n of selected) {
    if (!waves.has(n)) throw new Error(`切片文件里没有第 ${n} 波；已知波次 ${[...waves.keys()].join(', ')}`)
  }
  if (!existsSync(RUNTIME)) throw new Error(`运行副本不存在：${RUNTIME}；先跑一次桌面端或 rebuild.cmd profile`)
  const before = readFileSync(RUNTIME, 'utf8')
  if (!existsSync(BACKUP)) copyFileSync(RUNTIME, BACKUP)
  const base = stripBlock(before).trimEnd()
  const block = [
    '',
    `${BEGIN}（generated by lcoder/scripts/profile-slice.mjs；改切片请改 desktop-profile.slice.yml）`,
    ...selected.map(n => `# wave: ${n}`),
    ...selected.flatMap(n => ['', `# ── wave ${n} ──`, waves.get(n)]),
    END,
    '',
  ].join('\n')
  const next = `${base}\n${block}`
  parseRows(next)
  writeFileSync(RUNTIME, next)
  console.log(`已应用第 ${selected.join(', ')} 波 → ${RUNTIME}`)
  console.log(`原文件备份在 ${BACKUP}（restore 不会删它）`)
}

function restore() {
  if (!existsSync(RUNTIME)) throw new Error(`运行副本不存在：${RUNTIME}`)
  const before = readFileSync(RUNTIME, 'utf8')
  const begin = before.indexOf(BEGIN)
  if (begin < 0) {
    console.log('没有找到 T-177 切片块，运行副本未改')
    return
  }
  const prefix = before.slice(0, begin)
  // 副本没被换过内容时按备份原字节还原。桌面端启动时会把 YAML 重新序列化
  // （折行会变），所以这里比语义而不是比字节。
  if (existsSync(BACKUP)) {
    const backup = readFileSync(BACKUP, 'utf8')
    try {
      if (JSON.stringify(parseRows(prefix)) === JSON.stringify(parseRows(backup))) {
        writeFileSync(RUNTIME, backup)
        console.log(`已按备份原字节还原 → ${RUNTIME}`)
        return
      }
    } catch { /* 解析失败就退回文本去掉块 */ }
  }
  parseRows(prefix)
  writeFileSync(RUNTIME, prefix.replace(/\n+$/, '\n'))
  console.log(`已移除 T-177 切片块（副本已被重写，按去掉块的内容还原）→ ${RUNTIME}`)
}

function status() {
  if (!existsSync(RUNTIME)) {
    console.log(`运行副本不存在：${RUNTIME}`)
    return
  }
  const text = readFileSync(RUNTIME, 'utf8')
  const begin = text.indexOf(BEGIN)
  if (begin < 0) {
    console.log('未应用任何切片（运行副本里没有 T-177 块）')
    return
  }
  const end = text.indexOf(END, begin)
  const block = text.slice(begin, end < 0 ? undefined : end)
  const waves = [...block.matchAll(/^# wave: (\d+)$/gm)].map(m => m[1])
  const rows = [...block.matchAll(/^- id: (\S+)/gm)].map(m => m[1])
  const disabled = [...block.matchAll(/^  disabled: true$/gm)].length
  console.log(`已应用波次：${waves.join(', ') || '（未标注）'}`)
  console.log(`块内条目 ${rows.length} 行，其中 disabled ${disabled} 行`)
  console.log(rows.join(', '))
}

/** Static upper bound: sum the built client.js of the wave's rows that ship a browser half. */
function estimate(selected) {
  const waves = readWaves()
  const dumpPath = join(ROOT, 'lcoder', 'logs', 'slice-dump-composed.yml')
  if (!existsSync(dumpPath)) {
    throw new Error(`缺少合成清单 ${dumpPath}；先用 --dump-config 导出一份（见 lcoder/profile-slice.md 的口径一节）`)
  }
  const require2 = createRequire(join(ROOT, 'packages', 'lcoder', 'kernel', 'package.json'))
  const YAML = require2('yaml')
  const rows = YAML.parseDocument(readFileSync(dumpPath, 'utf8'), {
    customTags: [{ tag: '!!js', resolve: value => String(value) }],
  }).toJS()
  const nameOf = new Map(rows.map(row => [row.id, row.name]))

  // package name -> its built client.js, if the package ships a browser half.
  const clientBundles = new Map()
  const scan = dir => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory() || entry.name === 'node_modules' || entry.name.startsWith('.')) continue
      const abs = join(dir, entry.name)
      if (existsSync(join(abs, 'package.json'))) {
        try {
          const pkg = JSON.parse(readFileSync(join(abs, 'package.json'), 'utf8'))
          const bundle = join(abs, 'lib', 'client.js')
          if (pkg.name && existsSync(bundle)) clientBundles.set(pkg.name, bundle)
        } catch { /* unreadable manifest is not this command's concern */ }
      } else {
        scan(abs)
      }
    }
  }
  scan(join(ROOT, 'packages'))

  let total = 0
  for (const n of selected) {
    const ids = [...waves.get(n).matchAll(/^- id: (\S+)$/gm)].map(m => m[1])
    console.log(`wave ${n}: ${ids.length} 行`)
    for (const id of ids) {
      const name = nameOf.get(id)
      if (name === undefined) {
        console.log(`  ${id}: 合成清单里没有这一行（已禁用或名字变了）`)
        continue
      }
      const file = clientBundles.get(name)
      const bytes = file === undefined ? 0 : readFileSync(file).length
      total += bytes
      console.log(`  ${id} → ${file === undefined ? '无客户端产物' : `${(bytes / 1024).toFixed(0)} KiB`}`)
    }
  }
  console.log(`合计客户端产物上界：${(total / 1024).toFixed(0)} KiB（未压缩，本检出构建）`)
}

const argv = process.argv.slice(2)
const command = argv[0]
const waves = []
for (let i = 1; i < argv.length; i += 1) {
  if (argv[i] === '--wave') waves.push(Number(argv[i + 1]))
}
try {
  if (command === 'apply') {
    const selected = waves.length ? waves : [1]
    apply(selected)
  } else if (command === 'restore') {
    restore()
  } else if (command === 'status') {
    status()
  } else if (command === 'estimate') {
    estimate(waves.length ? waves : [1])
  } else {
    throw new Error('用法：profile-slice.mjs <apply|restore|status|estimate> --wave <n>')
  }
} catch (error) {
  console.error(String(error instanceof Error ? error.message : error))
  process.exitCode = 1
}
